// @vitest-environment jsdom
import { describe, expect, it } from 'vitest';
import { sampleProject } from '../data/sampleProject';
import { standardTemplate, titleBlockHtml } from '../model/titleBlock';
import type { Project } from '../types';
import { buildSldSheetHtml } from './sldSheet';

/** The band along a drawing sheet's foot: the revision table and the title block share its rows, and the frame draws
 * its foot and right edge, so every line meets and none is drawn twice. The printed check is tests/pdf/sheetFrame.pdf.ts. */

const svg = '<svg viewBox="0 0 100 50"></svg>';
const history = Array.from({ length: 4 }, (_, i) => ({ id: 'ABCD'[i], date: `2026-10-0${i + 1}`, description: `Issue ${i + 1}` }));
const one = { no: 'E-SLD-001', title: 'SLD', count: 2, index: 1, history, legendSvg: '<svg viewBox="0 0 10 10"></svg>' };
const parse = (html: string) => new DOMParser().parseFromString(html, 'text/html');
const withTemplate = (t: ReturnType<typeof standardTemplate>): Project => ({ ...sampleProject, titleTemplates: [t], drawing: { ...sampleProject.drawing, titleTemplateId: t.id } });

describe('drawing sheet band', () => {
  it('puts the revisions and the title block in one table, row for row: newest revision first, the generated-by line last', () => {
    const rows = [...parse(buildSldSheetHtml(sampleProject, svg, 'A3', one)).querySelectorAll('.frame > table.tb.band tr')];
    expect(rows).toHaveLength(6);
    for (const r of rows) {
      const cells = [...r.children], first = cells.findIndex((c) => c.classList.contains('t'));
      expect(first).toBeGreaterThan(0);
      expect(cells.slice(0, first).every((c) => c.classList.contains('r'))).toBe(true);
      expect(cells[first].classList.contains('l')).toBe(true); // the block's left edge
      expect(cells[cells.length - 1].classList.contains('e')).toBe(true); // its right edge, the frame's
    }
    expect(rows.map((r) => r.querySelector('td.r')!.textContent)).toEqual(['Rev', 'D', 'C', 'B', 'A', expect.stringContaining('Generated by LV Design Studio')]);
  });

  it('leaves the band\'s foot and right edge to the frame, and brings the legend column down to the band', () => {
    const html = buildSldSheetHtml(sampleProject, svg, 'A3', one), doc = parse(html);
    expect(html).toContain('.tb td.e { border-right: 0; }');
    expect(html).toContain('.tb tr:last-child td { border-bottom: 0; }');
    // The frame stacks the drawing area on the band; the legend column runs the drawing area's full height.
    expect([...doc.querySelector('.frame')!.children].map((c) => c.className)).toEqual(['body', 'tb band']);
    expect(doc.querySelector('.body > .side')).not.toBeNull();
    expect(html).toMatch(/\.side \{ position: absolute; right: 0; top: 0; width: [\d.]+mm; bottom: 0;/);
    expect(html).not.toMatch(/bottom: (44|47)mm/);
  });

  it('a template keeps its own grid, in the frame\'s corner: its right and bottom edges are the frame\'s', () => {
    const t = standardTemplate();
    const cellsOf = (html: string) => [...parse(html).querySelectorAll('td')].map((c) => c.getAttribute('style') ?? '');
    const framed = cellsOf(titleBlockHtml(t, sampleProject, {}, true)), plain = cellsOf(titleBlockHtml(t, sampleProject));
    expect(plain.some((s) => /border-(right|bottom):0/.test(s))).toBe(false); // the template designer's preview keeps its outline
    expect(framed.filter((s) => s.includes('border-right:0'))).toHaveLength(t.cells.filter((c) => c.c + (c.cs ?? 1) === t.cols.length).length);
    expect(framed.filter((s) => s.includes('border-bottom:0'))).toHaveLength(t.cells.filter((c) => c.r + (c.rs ?? 1) === t.rows.length).length);
    expect(framed.filter((s) => s.includes('border-top-width:0.5mm'))).toHaveLength(t.cells.filter((c) => c.r === 0).length);
    // On the sheet the revision table beside it follows its rows.
    const doc = parse(buildSldSheetHtml(withTemplate(t), svg, 'A3', one));
    expect([...doc.querySelectorAll('.band .rv tr')].map((r) => (r as HTMLElement).style.height)).toEqual(t.rows.map((h) => `${h}mm`));
    expect(doc.querySelector('.rvx')).toBeNull();
  });

  it('a template lower than the revision table: the table stands taller, closed down to the template', () => {
    const low = { ...standardTemplate(), id: 'low', rows: [8, 8], cells: [{ id: 'a', r: 0, c: 0, cs: 4, kind: 'text' as const, text: '{Project}' }, { id: 'b', r: 1, c: 0, cs: 4, kind: 'text' as const, text: '{DrawingNo}' }] };
    const html = buildSldSheetHtml(withTemplate(low), svg, 'A3', one), doc = parse(html);
    const band = doc.querySelector<HTMLElement>('.band.cb')!, rise = (9 + 4 * 4.5) - 16;
    expect(band.style.height).toBe(`${9 + 4 * 4.5}mm`);
    const close = doc.querySelector<HTMLElement>('.rvx')!;
    expect([close.style.bottom, close.style.height]).toEqual(['16mm', `${rise}mm`]);
    expect(html).toContain(`bottom: -${rise}mm;`); // the legend column comes down to the template
  });
});
